#!/usr/bin/env sh
# Regenerates docs/traceability.md from `// REQ:` tags in tests.
# Run from the repository root: sh tools/trace.sh
set -eu

out=docs/traceability.md
tmp=$(mktemp)

for f in $(grep -rl "REQ:" crates --include=*.rs); do
    awk -v file="$f" '
        /\/\/ REQ:/ { sub(/.*\/\/ REQ: */, ""); reqs = $0; next }
        reqs != "" && /fn [a-z_0-9]+\(/ {
            match($0, /fn [a-z_0-9]+/)
            name = substr($0, RSTART + 3, RLENGTH - 3)
            n = split(reqs, a, /, */)
            for (i = 1; i <= n; i++) print a[i] "\t" name "\t" file
            reqs = ""
        }' "$f"
done | sort > "$tmp"

{
    echo "# Traceability"
    echo
    echo "Generated by \`sh tools/trace.sh\` from \`// REQ:\` tags in tests."
    echo "Requirements verified by demonstration (D) or inspection (I) are listed in"
    echo "[requirements.md](requirements.md) with how they are checked."
    echo
    echo "| Requirement | Test | File |"
    echo "| --- | --- | --- |"
    awk -F '\t' '{ printf "| %s | `%s` | %s |\n", $1, $2, $3 }' "$tmp"
    echo
    echo "## Requirements without an automated test"
    echo
    grep -oE '^\| [A-Z]+-[0-9]+' docs/requirements.md | tr -d '| ' | sort > "$tmp.reqs"
    cut -f1 "$tmp" | sort -u | comm -13 - "$tmp.reqs" | sed 's/^/- /'
} > "$out"

rm -f "$tmp" "$tmp.reqs"
echo "wrote $out"
